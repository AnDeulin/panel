# ХУК 3 — напоминалка о сортировке задания (событие UserPromptSubmit).
# Что делает: смотрит сообщение пользователя. Есть признаки крупной задачи (исследование, стратегия,
#   план, сайт, агент, набор клиентских текстов) — подкладывает Claude одну строку-напоминание:
#   «если это новое крупное задание — сначала цель и вопросы, без поиска».
#   Нет признаков — ничего не выводит: ноль токенов.
# Зачем: в длинном диалоге правила из начала «тускнеют»; напоминание рядом с сообщением надёжнее.
# Решение «мелкое или крупное» всё равно принимает Claude: на правке или вопросе он ответит сразу.
#
# ВЫКЛЮЧАТЕЛЬ: поменяйте $true на $false, чтобы отключить напоминалку.
$enabled = $true

# Признаки крупной задачи. Пополнять можно: одна строка — один признак (регулярное выражение).
$signals = @(
    'исследова', 'исследуй', 'изучи', 'методолог',
    'стратеги', 'бизнес.?план',
    '(сделай|составь|разработай|напиши|придумай|подготовь) план',
    'план (продвижения|запуска|развития|действий|работ|контента)',
    'разработай', 'спроектируй',
    'придумай (систему|воронку|продукт|бота|агента|сайт|оффер|стратегию)',
    '(сделай|создай|собери|запусти) (сайт|лендинг|бота|агента|систему|воронку|курс|школу|рекламу|рассылку)',
    'лендинг', 'воронк', '\bsmm\b', 'смм', 'контент.?план',
    'маркетинг.?аудит', 'полный маркетинг', 'маркетинг по полной', 'глубокий маркетинг', '/аудит',
    'custdev', 'кастдев', 'jtbd', 'анализ конкурент',
    'запуск (продукта|школы|курса|рекламы|бизнеса)',
    'ии.?агент', 'ai.?agent', 'серия (постов|писем)', 'рассылк', 'оффер',
    'собери панель', 'нужна панель', '/panel'
)

$reminder = 'Напоминание: похоже на крупную задачу. Если это НОВОЕ крупное задание — сначала навык panel; первой строкой сразу скажи, что задача крупная и сначала согласуешь цель. Первый ответ готовь быстро: только как понял, цель, 2–4 вопроса и что сделаешь после одобрения — задачу до одобрения не решай, без интернета и разведки. Вопрос, правка или следующий шаг уже одобренной работы — отвечай сразу.'

# Принцип безопасности: любая ошибка — молча выходим, сообщение пользователя никогда не блокируем.
try {
    if (-not $enabled) { exit 0 }

    # Вход читаем байтами и декодируем как UTF-8: иначе PowerShell 5.1 портит кириллицу.
    $stdin = [Console]::OpenStandardInput()
    $buf = New-Object System.IO.MemoryStream
    $stdin.CopyTo($buf)
    $raw = [System.Text.Encoding]::UTF8.GetString($buf.ToArray())
    if ([string]::IsNullOrWhiteSpace($raw)) { exit 0 }

    $data = $raw | ConvertFrom-Json
    $prompt = [string]$data.prompt
    if ([string]::IsNullOrWhiteSpace($prompt)) { exit 0 }

    if ($prompt.ToLowerInvariant() -notmatch ($signals -join '|')) { exit 0 }

    # Ответ — JSON только из ASCII-символов (кириллица как \uXXXX): не зависит от кодировки консоли.
    $sb = New-Object System.Text.StringBuilder
    foreach ($ch in $reminder.ToCharArray()) {
        $c = [int]$ch
        if ($c -eq 34) { [void]$sb.Append('\"') }
        elseif ($c -eq 92) { [void]$sb.Append('\') }
        elseif ($c -lt 32 -or $c -gt 126) { [void]$sb.Append(('\u{0:x4}' -f $c)) }
        else { [void]$sb.Append($ch) }
    }
    $json = '{"hookSpecificOutput":{"hookEventName":"UserPromptSubmit","additionalContext":"' + $sb.ToString() + '"}}'
    [Console]::Out.Write($json)
    exit 0
} catch {
    exit 0
}
